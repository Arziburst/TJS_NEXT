#Requires -Version 7
<#
.SYNOPSIS
Starts this worktree's own Supabase stack tjs-<n> and writes its .env.local.

.DESCRIPTION
n is the leading number of the worktree folder (<n>-<type>-<slug>) or -IssueNumber.
Ports: base 41000 + (n mod 200) * 10 (shadow +0, API +1, DB +2, Studio +3, mail +4, analytics +7,
pooler +9), dev server 3000 + n. Refuses to start when a port is in a Windows excluded range or in use.
Rewrites the worktree's supabase/config.toml (project_id, ports, auth URLs) and marks it skip-worktree
so the rewrite is never committed; runs `supabase start`; writes the stack's values into a managed
block of .env.local. Safe to re-run.

.EXAMPLE
npm run supabase:start:worktree
npm run supabase:start:worktree -- -IssueNumber 207
#>
[CmdletBinding()]
param(
    [int]$IssueNumber
)

$ErrorActionPreference = 'Stop'
. "$PSScriptRoot/TjsStack.ps1"

$repoRoot = Get-TjsRepoRoot
if (-not (Test-TjsLinkedWorktree -Path $repoRoot)) {
    throw "$repoRoot is the main checkout: it uses the shared stack tjs-main (npm run supabase:start). This script is for linked worktrees only."
}

$n = Resolve-TjsIssueNumber -IssueNumber $IssueNumber -RepoRoot $repoRoot
$projectId = "tjs-$n"
$ports = Get-TjsStackPorts -IssueNumber $n
$mainPorts = Get-TjsMainPorts
$configPath = Join-Path $repoRoot 'supabase/config.toml'
$envPath = Join-Path $repoRoot '.env.local'

Write-Host "Stack ${projectId}: API $($ports.api), DB $($ports.db), Studio $($ports.studio), mail $($ports.mail), dev server $($ports.dev)"

# 1. Ports. A running tjs-<n> holds its own ports, so the check only applies before the first start.
$running = @(Get-TjsStackContainers -ProjectId $projectId | Where-Object State -eq 'running')
if ($running.Count -eq 0) {
    $toCheck = @($ports.shadow, $ports.api, $ports.db, $ports.studio, $ports.mail, $ports.pooler)
    $problems = @(Get-TjsPortProblems -Ports $toCheck)
    if ($problems.Count -gt 0) {
        $problems | ForEach-Object { Write-Host "  - $_" }
        throw "Refusing to start ${projectId}: its ports are not free. Stop what holds them (another task with the same n mod 200?) or, for an excluded range, ask the coordinator about the port base."
    }
} else {
    Write-Host "$projectId is already running ($($running.Count) containers); skipping the port check."
}

# 2. config.toml
$content = Get-Content -LiteralPath $configPath -Raw
$currentId = Get-TjsConfigProjectId -ConfigPath $configPath
if ($currentId -eq $projectId) {
    if ($content -notmatch "(?m)^port = $($ports.api)\s*$") {
        throw "config.toml says $projectId but not API port $($ports.api). Restore it: git update-index --no-skip-worktree supabase/config.toml; git checkout -- supabase/config.toml"
    }
    Write-Host "config.toml already points at $projectId."
} elseif ($currentId -eq 'tjs-main') {
    function Set-Once([string]$text, [string]$pattern, [string]$replacement, [string]$what) {
        $count = [regex]::Matches($text, $pattern).Count
        if ($count -ne 1) { throw "config.toml: expected exactly one $what, found $count." }
        [regex]::Replace($text, $pattern, $replacement)
    }
    $content = Set-Once $content '(?m)^project_id = "tjs-main"' "project_id = `"$projectId`"" 'project_id = "tjs-main"'
    foreach ($key in $script:TjsPortOffsets.Keys) {
        $prefix = if ($key -eq 'shadow') { 'shadow_port' } else { 'port' }
        $content = Set-Once $content "(?m)^$prefix = $($mainPorts[$key])(?=\s*$)" "$prefix = $($ports[$key])" "'$prefix = $($mainPorts[$key])'"
    }
    $urlPattern = '(?<=//(?:127\.0\.0\.1|localhost):)3000(?=[/"])'
    if ([regex]::Matches($content, $urlPattern).Count -lt 2) { throw 'config.toml: auth site_url / redirect URLs on port 3000 not found.' }
    $content = [regex]::Replace($content, $urlPattern, [string]$ports.dev)
    [IO.File]::WriteAllText($configPath, $content, [Text.UTF8Encoding]::new($false))
    Write-Host "config.toml rewritten for $projectId."
} else {
    throw "config.toml points at '$currentId', not tjs-main or $projectId. Restore it: git update-index --no-skip-worktree supabase/config.toml; git checkout -- supabase/config.toml"
}

& git -C $repoRoot update-index --skip-worktree -- supabase/config.toml
if ($LASTEXITCODE -ne 0) { throw 'git update-index --skip-worktree failed.' }

# 3. Start
Push-Location $repoRoot
try {
    & npx supabase start
    if ($LASTEXITCODE -ne 0) { throw "supabase start failed ($LASTEXITCODE)." }

    $statusLines = & npx supabase status -o env 2>$null
    if ($LASTEXITCODE -ne 0) { throw "supabase status failed ($LASTEXITCODE)." }
} finally { Pop-Location }

# 4. .env.local: only the managed block is replaced; other lines stay.
$values = [ordered]@{}
foreach ($line in $statusLines) {
    if ($line -match '^([A-Z][A-Z0-9_]*)="?(.*?)"?\s*$') { $values[$Matches[1]] = $Matches[2] }
}
if (-not $values.Contains('API_URL')) { throw "supabase status -o env returned no API_URL:`n$($statusLines -join "`n")" }

$begin = '# >>> tjs-stack (generated by npm run supabase:start:worktree; do not edit inside this block)'
$end = '# <<< tjs-stack'
$block = [System.Collections.Generic.List[string]]::new()
$block.Add($begin)
$block.Add("SUPABASE_PROJECT_ID=$projectId")
foreach ($k in $values.Keys) { $block.Add("$k=`"$($values[$k])`"") }
$block.Add("PORT=$($ports.dev)")
$block.Add("NEXT_PUBLIC_SITE_URL=http://localhost:$($ports.dev)")
$block.Add($end)

$kept = @()
if (Test-Path -LiteralPath $envPath) {
    $inBlock = $false
    foreach ($line in Get-Content -LiteralPath $envPath) {
        if ($line -eq $begin) { $inBlock = $true; continue }
        if ($line -eq $end) { $inBlock = $false; continue }
        if (-not $inBlock) { $kept += $line }
    }
}
$out = @($block)
if ($kept.Count -gt 0) { $out += @('') + $kept }
[IO.File]::WriteAllText($envPath, (($out -join "`n").TrimEnd() + "`n"), [Text.UTF8Encoding]::new($false))

Write-Host ''
Write-Host "$projectId is up. Studio http://127.0.0.1:$($ports.studio)  API $($values['API_URL'])"
Write-Host ".env.local written. Dev server: npm run dev -- -p $($ports.dev)"
